VECTORS = Path(__file__).resolve().parents[3] / "test-vectors" / "integrity"


def load(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((VECTORS / name).read_text(encoding="utf-8"))
    return data


def test_every_expected_vector_file_exists() -> None:
    names = {p.name for p in VECTORS.glob("*.json")}
    assert names == {
        "sha256.json", "domain.json", "canonical.json", "normalize.json", "leaves.json",
        "merkle.json", "echo.json", "chain.json", "records.json", "worked_example.json",
    }  # fmt: skip


def test_files_say_they_are_generated() -> None:
    for path in VECTORS.glob("*.json"):
        assert "Generated by scripts/make_test_vectors.py" in load(path.name)["generated"]


@pytest.mark.parametrize("v", load("sha256.json")["vectors"], ids=lambda v: v["name"])
def test_sha256_vectors(v: dict[str, Any]) -> None:
    data = bytes.fromhex(v["input_hex"])
    assert to_hex(sha256(data)) == v["sha256"] == hashlib.sha256(data).hexdigest()


def test_sha256_vectors_include_the_published_ones() -> None:
    by_name = {v["name"]: v["sha256"] for v in load("sha256.json")["vectors"]}
    assert by_name["empty"] == "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    assert by_name["abc"] == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"


@pytest.mark.parametrize("v", load("domain.json")["vectors"], ids=lambda v: v["name"])
def test_domain_vectors(v: dict[str, Any]) -> None:
    parts = [bytes.fromhex(p) for p in v["parts_hex"]]
    assert to_hex(domain_hash(v["prefix"], *parts)) == v["hash"]
    assert v["hash"] == hashlib.sha256(bytes([v["prefix"]]) + b"".join(parts)).hexdigest()


def test_export_digest_vectors_are_plain_sha256() -> None:
    for v in load("domain.json")["export_digests"]:
        raw = bytes.fromhex(v["raw_hex"])
        assert to_hex(export_digest(raw)) == v["export_digest"] == hashlib.sha256(raw).hexdigest()


def test_rejected_prefixes() -> None:
    for v in load("domain.json")["rejected"]:
        with pytest.raises(ValueError):
            domain_hash(v["prefix"], *[bytes.fromhex(p) for p in v["parts_hex"]])


@pytest.mark.parametrize("v", load("canonical.json")["vectors"], ids=lambda v: v["name"])
def test_canonical_vectors(v: dict[str, Any]) -> None:
    out = canonicalize(json.loads(v["input_json"]))
    assert out.hex() == v["canonical_hex"]
    assert out.decode() == v["canonical_utf8"]


@pytest.mark.parametrize("v", load("canonical.json")["rejected"], ids=lambda v: v["name"])
def test_out_of_range_integers_are_rejected(v: dict[str, Any]) -> None:
    with pytest.raises(CanonicalizationError):
        canonicalize(json.loads(v["input_json"]))


@pytest.mark.parametrize("v", load("normalize.json")["vectors"], ids=lambda v: v["name"])
def test_normalisation_vectors(v: dict[str, Any]) -> None:
    out = canonical_record(json.loads(v["input_json"]))
    assert out.hex() == v["canonical_hex"]
    assert to_hex(sha256(out)) == v["record_digest"]


def test_nfc_and_non_nfc_input_give_the_same_record_but_not_the_same_raw_canonical_form() -> None:
    by_name = {v["name"]: v for v in load("normalize.json")["vectors"]}
    already = by_name["already nfc"]["canonical_hex"]
    assert by_name["decomposed becomes nfc"]["canonical_hex"] == already
    raw_decomposed = canonicalize(json.loads(by_name["decomposed becomes nfc"]["input_json"]))
    assert raw_decomposed.hex() != already


@pytest.mark.parametrize("v", load("leaves.json")["vectors"], ids=lambda v: v["name"])
def test_leaf_vectors(v: dict[str, Any]) -> None:
    salt = bytes.fromhex(v["salt_hex"])
    if v["kind"] == "file":
        raw = bytes.fromhex(v["payload_hex"])
        assert to_hex(file_leaf(v["prefix"], salt, raw)) == v["leaf"]
        digest = hashlib.sha256(raw).digest()
    else:
        record = json.loads(v["record_json"])
        assert to_hex(record_leaf(v["prefix"], salt, record)) == v["leaf"]
        digest = hashlib.sha256(canonical_record(record)).digest()
    assert v["payload_digest"] == digest.hex()
    assert v["leaf"] == hashlib.sha256(bytes([v["prefix"]]) + salt + digest).hexdigest()


