@pytest.mark.parametrize("tree", load("merkle.json")["trees"], ids=lambda t: f"n={t['leaf_count']}")
def test_merkle_trees_and_proofs(tree: dict[str, Any]) -> None:
    leaves = [from_hex(x) for x in tree["leaves"]]
    root = from_hex(tree["root"])
    assert merkle_root(leaves) == root
    for proof in tree["proofs"]:
        steps = tuple(ProofStep(from_hex(s["sibling"]), s["side"]) for s in proof["steps"])
        assert inclusion_proof(leaves, proof["index"]) == steps
        assert verify_inclusion(leaves[proof["index"]], steps, root)


def test_merkle_proof_checks() -> None:
    for check in load("merkle.json")["proof_checks"]:
        steps = [ProofStep(from_hex(s["sibling"]), s["side"]) for s in check["steps"]]
        result = verify_inclusion(from_hex(check["leaf"]), steps, from_hex(check["root"]))
        assert result is check["valid"], check["name"]


def test_merkle_node_example_and_empty_tree() -> None:
    data = load("merkle.json")
    ex = data["node_example"]
    assert to_hex(node_hash(from_hex(ex["left"]), from_hex(ex["right"]))) == ex["node"]
    assert (
        ex["node"]
        == hashlib.sha256(b"\x01" + from_hex(ex["left"]) + from_hex(ex["right"])).hexdigest()
    )
    for v in data["rejected"]:
        with pytest.raises(MerkleError):
            merkle_root([bytes.fromhex(x) for x in v["leaves"]])


def test_merkle_vectors_cover_the_spec_sizes() -> None:
    sizes = {t["leaf_count"] for t in load("merkle.json")["trees"]}
    assert {1, 2, 3, 4, 5, 7, 9, 16} <= sizes


@pytest.mark.parametrize("v", load("echo.json")["vectors"], ids=lambda v: v["name"])
def test_echo_vectors(v: dict[str, Any]) -> None:
    if "recap_json" in v:
        assert to_hex(recap_hash(json.loads(v["recap_json"]))) == v["recap_hash"]
    assert derive_echo_code(from_hex(v["recap_hash"])) == v["echo_code"]
    assert len(v["echo_code"]) == 4 and set(v["echo_code"]) <= set(CROCKFORD)


def test_echo_code_normalisation_and_rejection() -> None:
    data = load("echo.json")
    for v in data["code_normalisation"]:
        assert normalize_code(v["input"]) == v["normalized"]
    for v in data["rejected"]:
        with pytest.raises(ValueError):
            derive_echo_code(bytes.fromhex(v["recap_hash_hex"]))


def test_chain_vectors() -> None:
    data = load("chain.json")
    assert data["genesis"] == "00" * 32
    pairs = []
    for entry in data["versions"]:
        digest = terms_digest(json.loads(entry["terms_json"]))
        assert to_hex(digest) == entry["terms_digest"]
        pairs.append((digest, from_hex(entry["root"])))
    links = chain_links(pairs)
    assert [to_hex(x) for x in links] == [e["link"] for e in data["versions"]]
    tampered = [from_hex(x) for x in data["tampered_first_terms"]["links"]]
    assert all(a != b for a, b in zip(tampered, links, strict=True)), "every link changes"


def test_plain_record_vectors() -> None:
    for v in load("records.json")["vectors"]:
        assert to_hex(plain_record_hash(v["prefix"], json.loads(v["record_json"]))) == v["hash"]


def test_worked_example_vector() -> None:
    ex = load("worked_example.json")
    salts = [bytes.fromhex(s) for s in ex["salts_hex"]]
    leaves = [record_leaf(0x10, s, p) for s, p in zip(salts, ex["payloads"], strict=True)]
    assert [to_hex(x) for x in leaves] == ex["leaves"]
    assert to_hex(node_hash(leaves[0], leaves[1])) == ex["node_1_2"]
    assert to_hex(merkle_root(leaves)) == ex["root"]
    assert canonicalize(ex["payloads"][0]).decode() == ex["payload_1_canonical"]
