import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SCRIPT = ROOT / "scripts" / "make_test_vectors.py"
spec = importlib.util.spec_from_file_location("make_test_vectors", SCRIPT)
assert spec is not None and spec.loader is not None
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)


def test_committed_vectors_equal_freshly_generated_ones() -> None:
    """The files cannot be edited by hand: they must equal the output of the real code."""
    fresh = mod.build_vectors()
    on_disk = {p.name: p.read_text(encoding="utf-8") for p in (ROOT / mod.OUT_DIR).glob("*.json")}
    assert on_disk == fresh


def test_generation_is_deterministic() -> None:
    assert mod.build_vectors() == mod.build_vectors()


def test_the_spec_worked_example_matches_the_vectors() -> None:
    example = json.loads(mod.build_vectors()["worked_example.json"])
    spec_text = (ROOT / mod.SPEC_FILE).read_text(encoding="utf-8")
    assert mod.updated_spec(spec_text, example) == spec_text
    assert "<generated by scripts/make_test_vectors.py>" not in spec_text


def test_check_mode_passes_on_the_repository() -> None:
    assert mod.main(["--check"]) == 0


def test_check_mode_detects_a_hand_edited_vector(tmp_path: Path) -> None:
    out = tmp_path / mod.OUT_DIR
    out.mkdir(parents=True)
    for name, text in mod.build_vectors().items():
        (out / name).write_text(text, encoding="utf-8")
    assert mod.main(["--root", str(tmp_path), "--check"]) == 0
    sha = out / "sha256.json"
    sha.write_text(
        sha.read_text(encoding="utf-8").replace("e3b0c442", "e3b0c443"), encoding="utf-8"
    )
    assert mod.main(["--root", str(tmp_path), "--check"]) == 1


def test_write_mode_creates_every_file(tmp_path: Path) -> None:
    assert mod.main(["--root", str(tmp_path)]) == 0
    written = {p.name for p in (tmp_path / mod.OUT_DIR).glob("*.json")}
    assert written == set(mod.BUILDERS)
