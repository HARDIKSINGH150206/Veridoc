"""Generate the integrity test vectors by running the real code. Never edit the files by hand.

Writes JSON files into test-vectors/integrity/ and keeps the worked example in
docs/INTEGRITY_SPEC.md in step. Python and JavaScript must both reproduce every vector.

    uv run python scripts/make_test_vectors.py            write the files
    uv run python scripts/make_test_vectors.py --check    fail if the files or the spec differ
"""

