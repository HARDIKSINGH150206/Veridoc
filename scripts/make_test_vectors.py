def build_vectors() -> dict[str, str]:
    """File name to file text, built by running the real code."""
    files = {}
    for name, builder in BUILDERS.items():
        body = {"generated": HEADER, **builder()}
        files[name] = json.dumps(body, indent=2, ensure_ascii=True) + "\n"
    return files


def spec_block(example: dict[str, Any]) -> str:
    rows = [
        "| Item | Value |",
        "|---|---|",
        f"| Payload 1 (JCS) | `{example['payload_1_canonical']}` |",
        f"| Leaf 1 | `{example['leaves'][0]}` |",
        f"| Leaf 2 | `{example['leaves'][1]}` |",
        f"| Leaf 3 | `{example['leaves'][2]}` |",
        f"| Node(1,2) | `{example['node_1_2']}` |",
        f"| Root (node(1,2) with leaf 3 carried up) | `{example['root']}` |",
    ]
    return "\n".join(rows)


def updated_spec(text: str, example: dict[str, Any]) -> str:
    pattern = re.compile(re.escape(SPEC_START) + r".*?" + re.escape(SPEC_END), re.DOTALL)
    block = f"{SPEC_START}\n{spec_block(example)}\n{SPEC_END}"
    if not pattern.search(text):
        raise SystemExit(f"{SPEC_FILE} has no {SPEC_START} ... {SPEC_END} block")
    return pattern.sub(lambda _: block, text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the integrity test vectors.")
    parser.add_argument("--root", default=str(ROOT))
    parser.add_argument("--check", action="store_true", help="only compare, do not write")
    args = parser.parse_args(argv)
    root = Path(args.root)
    out = root / OUT_DIR
    files = build_vectors()
    example = json.loads(files["worked_example.json"])
    spec_path = root / SPEC_FILE
    new_spec = (
        updated_spec(spec_path.read_text(encoding="utf-8"), example) if spec_path.exists() else None
    )

    if args.check:
        stale = [
            n
            for n, text in files.items()
            if not (out / n).exists() or (out / n).read_text(encoding="utf-8") != text
        ]
        if new_spec is not None and spec_path.read_text(encoding="utf-8") != new_spec:
            stale.append(SPEC_FILE)
        extra = [p.name for p in out.glob("*.json") if p.name not in files] if out.exists() else []
        for name in stale:
            print(f"out of date: {name}")
        for name in extra:
            print(f"not generated (remove it): {name}")
        if stale or extra:
            print("Run: uv run python scripts/make_test_vectors.py")
            return 1
        print(f"make_test_vectors: {len(files)} files up to date")
        return 0

    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
    if new_spec is not None:
        spec_path.write_text(new_spec, encoding="utf-8")
    print(f"wrote {len(files)} files to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
