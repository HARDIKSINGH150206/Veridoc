# Characters are built with chr() so that no formatter or tool can change them.
E_ACUTE = chr(0xE9)
E_COMBINING = "e" + chr(0x301)
QA = chr(0x0958)  # a Devanagari letter that NFC keeps decomposed (composition exclusion)
ANGSTROM = chr(0x212B)  # normalises to U+00C5
HINDI = "नमस्ते दुनिया"
KANNADA = "ನಮಸ್ಕಾರ"


def salt(i: int) -> bytes:
    return bytes([i]) * 16


def fake_hash(label: str) -> bytes:
    """A deterministic 32-byte value for vectors; not evidence."""
    return sha256(label.encode())


def jtext(value: Any) -> str:
    """JSON text with every non-ASCII character escaped, so the files are readable and exact."""
    return json.dumps(value, ensure_ascii=True, separators=(",", ":"))


def number_table() -> list[tuple[str, str]]:
    bits = [
        "0000000000000000",
        "8000000000000000",
        "0000000000000001",
        "8000000000000001",
        "7fefffffffffffff",
        "ffefffffffffffff",
        "4340000000000000",
        "c340000000000000",
        "4430000000000000",
        "44b52d02c7e14af5",
        "44b52d02c7e14af6",
        "44b52d02c7e14af7",
        "444b1ae4d6e2ef4e",
        "444b1ae4d6e2ef4f",
        "444b1ae4d6e2ef50",
        "3eb0c6f7a0b5ed8c",
        "3eb0c6f7a0b5ed8d",
        "41b3de4355555553",
        "41b3de4355555554",
        "41b3de4355555555",
        "41b3de4355555556",
        "41b3de4355555557",
        "becbf647612f3696",
        "43143ff3c1cb0959",
    ]
    out = []
    for b in bits:
        (value,) = struct.unpack(">d", bytes.fromhex(b))
        out.append((b, json.dumps(value)))
    return out


