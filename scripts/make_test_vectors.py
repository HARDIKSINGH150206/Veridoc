def sha256_vectors() -> dict[str, Any]:
    inputs = {
        "empty": b"",
        "abc": b"abc",
        "two blocks": b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq",
        "hindi utf-8": HINDI.encode(),
        "crlf and binary": b"line one\r\nline two\r\n\xff\x00\x01",
    }
    return {
        "description": "SHA-256 of raw bytes",
        "vectors": [
            {"name": n, "input_hex": b.hex(), "sha256": to_hex(sha256(b))}
            for n, b in inputs.items()
        ],
    }


def domain_vectors() -> dict[str, Any]:
    vectors = []
    for name, prefix in PREFIXES.items():
        parts = [b"first part", b"second part"]
        vectors.append(
            {
                "name": name,
                "prefix": prefix,
                "parts_hex": [p.hex() for p in parts],
                "hash": to_hex(domain_hash(prefix, *parts)),
            }
        )
    raw_exports = {
        "export with crlf": ("WhatsApp line one\r\nline two " + HINDI + "\r\n").encode(),
        "export with invalid utf-8": b"\xff\xfe\x00 not text",
    }
    exports = [
        {"name": n, "raw_hex": b.hex(), "export_digest": to_hex(export_digest(b))}
        for n, b in raw_exports.items()
    ]
    rejected = [
        {"name": "reserved prefix 0x00", "prefix": 0, "parts_hex": ["00"]},
        {"name": "undefined prefix 0x02", "prefix": 2, "parts_hex": ["00"]},
        {"name": "undefined prefix 0x99", "prefix": 0x99, "parts_hex": ["00"]},
    ]
    return {
        "description": "domain_hash(prefix, parts) for every prefix; plain SHA-256 export digests",
        "vectors": vectors,
        "export_digests": exports,
        "rejected": rejected,
    }


def canonical_vectors() -> dict[str, Any]:
    cases: dict[str, Any] = {
        "empty object": {},
        "empty array": [],
        "empty string": "",
        "key order": {"b": 1, "a": 2, "c": {"z": 1, "y": [3, {"b": 1, "a": 2}]}},
        "literals": {"n": None, "t": True, "f": False},
        "escapes": 'quote " backslash \\ newline \n tab \t control \x01 slash /',
        "hindi": {"text": HINDI},
        "kannada": {"text": KANNADA},
        "mixed hindi kannada english": {"k": KANNADA, "h": HINDI, "e": "hello"},
        "utf16 key order": {chr(0xE000): 1, chr(0x1F600): 2, "1": 3, chr(0x80): 4},
        "safe integer limits": [2**53 - 1, -(2**53 - 1)],
        "floats": [0.1, 1.5, 1e30, 4.5, 0.002, 1e-27, 333333333.3333333],
        "money as string": {"paise": "99999999999999999999"},
    }
    vectors = []
    for name, value in cases.items():
        data = canonicalize(value)
        vectors.append(
            {
                "name": name,
                "input_json": jtext(value),
                "canonical_utf8": data.decode(),
                "canonical_hex": data.hex(),
            }
        )
    for bits, text in number_table():
        data = canonicalize([json.loads(text)])
        vectors.append(
            {
                "name": f"rfc8785 appendix b {bits}",
                "input_json": f"[{text}]",
                "canonical_utf8": data.decode(),
                "canonical_hex": data.hex(),
            }
        )
    rejected = []
    for name, text in {
        "integer 2^53": "9007199254740992",
        "integer 2^53 + 1": "9007199254740993",
        "negative integer -2^53": "-9007199254740992",
        "integer 10^20": "100000000000000000000",
        "nested out of range integer": '{"a":[1,{"b":18014398509481984}]}',
    }.items():
        try:
            canonicalize(json.loads(text))
        except CanonicalizationError:
            rejected.append({"name": name, "input_json": text})
        else:  # pragma: no cover - would mean the rule is not enforced
            raise SystemExit(f"expected {name} to be rejected")
    return {
        "description": "canonicalize(): pure RFC 8785, no normalisation",
        "vectors": vectors,
        "rejected": rejected,
    }


def normalize_vectors() -> dict[str, Any]:
    cases: dict[str, Any] = {
        "already nfc": {"t": E_ACUTE},
        "decomposed becomes nfc": {"t": E_COMBINING},
        "composed and decomposed give one record": {"t": E_COMBINING + E_ACUTE},
        "angstrom sign": {"t": ANGSTROM},
        "devanagari qa stays decomposed": {"t": QA},
        "hindi text": {"t": HINDI + " " + QA},
        "line endings": {"t": "a\r\nb\rc\nd"},
        "keys are not normalised": {E_COMBINING: E_COMBINING},
        "nested and arrays": {"a": [E_COMBINING, {"b": "x\r\ny"}, 5, None, True]},
        "non-string values untouched": {"n": 7, "f": 1.5, "t": True},
    }
    vectors = []
    for name, value in cases.items():
        data = canonical_record(value)
        vectors.append(
            {
                "name": name,
                "input_json": jtext(value),
                "canonical_utf8": data.decode(),
                "canonical_hex": data.hex(),
                "record_digest": to_hex(sha256(data)),
            }
        )
    return {
        "description": "canonical_record(): NFC and LF on string values, keys untouched, RFC 8785",
        "vectors": vectors,
    }


def leaf_vectors() -> dict[str, Any]:
    vectors: list[dict[str, Any]] = []
    record: JsonValue = {
        "id": 1,
        "sender": "A",
        "text": HINDI + " " + E_COMBINING,
        "ts": "2026-10-12T10:02:00+05:30",
    }
    raw = b"RIFF" + bytes(range(16)) + b"\r\n"
    for name, prefix in PREFIXES.items():
        if prefix not in SALTED_LEAF_PREFIXES:
            continue
        s = salt(prefix % 251 or 1)
        if name in {"VOICE_AUDIO", "ATTACHMENT"}:
            leaf = file_leaf(prefix, s, raw)
            vectors.append(
                {
                    "name": name,
                    "kind": "file",
                    "prefix": prefix,
                    "salt_hex": s.hex(),
                    "payload_hex": raw.hex(),
                    "payload_digest": to_hex(payload_digest(raw)),
                    "leaf": to_hex(leaf),
                }
            )
        else:
            data = canonical_record(record)
            vectors.append(
                {
                    "name": name,
                    "kind": "record",
                    "prefix": prefix,
                    "salt_hex": s.hex(),
                    "record_json": jtext(record),
                    "payload_digest": to_hex(payload_digest(data)),
                    "leaf": to_hex(record_leaf(prefix, s, record)),
                }
            )
    rejected: list[dict[str, Any]] = [
        {
            "name": "plain prefix used as a leaf",
            "prefix": 0x21,
            "salt_hex": salt(1).hex(),
            "digest_hex": to_hex(sha256(b"x")),
        },
        {
            "name": "salt too short",
            "prefix": 0x10,
            "salt_hex": "01" * 8,
            "digest_hex": to_hex(sha256(b"x")),
        },
        {
            "name": "digest too short",
            "prefix": 0x10,
            "salt_hex": salt(1).hex(),
            "digest_hex": "00" * 8,
        },
    ]
    for item in rejected:
        try:
            leaf_hash(
                item["prefix"], bytes.fromhex(item["salt_hex"]), bytes.fromhex(item["digest_hex"])
            )
        except ValueError:
            continue
        raise SystemExit(f"expected {item['name']} to be rejected")  # pragma: no cover
    return {
        "description": "salted leaves: H(prefix || salt || H(payload))",
        "vectors": vectors,
        "rejected": rejected,
    }


def merkle_vectors() -> dict[str, Any]:
    trees = []
    for count in (1, 2, 3, 4, 5, 6, 7, 8, 9, 16, 17):
        leaves = [fake_hash(f"leaf-{i}") for i in range(count)]
        proofs = []
        for index in range(count):
            proofs.append(
                {
                    "index": index,
                    "steps": [
                        {"sibling": to_hex(step.sibling), "side": step.side}
                        for step in inclusion_proof(leaves, index)
                    ],
                }
            )
        trees.append(
            {
                "leaf_count": count,
                "leaves": [to_hex(x) for x in leaves],
                "root": to_hex(merkle_root(leaves)),
                "proofs": proofs,
            }
        )
    leaves = [fake_hash(f"leaf-{i}") for i in range(6)]
    root = merkle_root(leaves)
    proof = inclusion_proof(leaves, 2)
    steps = [{"sibling": to_hex(s.sibling), "side": s.side} for s in proof]
    flipped = [dict(s) for s in steps]
    flipped[0]["side"] = "left" if steps[0]["side"] == "right" else "right"
    bad_sibling = [dict(s) for s in steps]
    bad_sibling[1]["sibling"] = to_hex(fake_hash("not the sibling"))
    checks = [
        {
            "name": "valid proof",
            "leaf": to_hex(leaves[2]),
            "steps": steps,
            "root": to_hex(root),
            "valid": True,
        },
        {
            "name": "wrong leaf",
            "leaf": to_hex(leaves[3]),
            "steps": steps,
            "root": to_hex(root),
            "valid": False,
        },
        {
            "name": "wrong root",
            "leaf": to_hex(leaves[2]),
            "steps": steps,
            "root": to_hex(fake_hash("x")),
            "valid": False,
        },
        {
            "name": "side flipped",
            "leaf": to_hex(leaves[2]),
            "steps": flipped,
            "root": to_hex(root),
            "valid": False,
        },
        {
            "name": "sibling changed",
            "leaf": to_hex(leaves[2]),
            "steps": bad_sibling,
            "root": to_hex(root),
            "valid": False,
        },
        {
            "name": "step dropped",
            "leaf": to_hex(leaves[2]),
            "steps": steps[:-1],
            "root": to_hex(root),
            "valid": False,
        },
        {
            "name": "step added",
            "leaf": to_hex(leaves[2]),
            "steps": [*steps, steps[0]],
            "root": to_hex(root),
            "valid": False,
        },
    ]
    a, b = leaves[0], leaves[1]
    try:
        merkle_root([])
    except MerkleError:
        pass
    else:  # pragma: no cover
        raise SystemExit("an empty tree must be rejected")
    return {
        "description": "Merkle roots, inclusion proofs and proof checks. Odd nodes are carried up.",
        "node_example": {"left": to_hex(a), "right": to_hex(b), "node": to_hex(node_hash(a, b))},
        "trees": trees,
        "proof_checks": checks,
        "rejected": [{"name": "empty tree", "leaves": []}],
    }


def echo_vectors() -> dict[str, Any]:
    recaps: dict[str, JsonValue] = {
        "english": {
            "lines": ["Hi, just confirming:", "50 mugs", "Delivery by 20 Sept"],
            "version": 1,
        },
        "hindi": {"lines": [HINDI, "डिलीवरी 20 सितंबर तक"], "version": 2},
        "decomposed text": {"lines": [E_COMBINING], "version": 1},
        "changed line": {
            "lines": ["Hi, just confirming:", "51 mugs", "Delivery by 20 Sept"],
            "version": 1,
        },
    }
    vectors = []
    for name, recap in recaps.items():
        h = recap_hash(recap)
        vectors.append(
            {
                "name": name,
                "recap_json": jtext(recap),
                "recap_hash": to_hex(h),
                "echo_code": derive_echo_code(h),
            }
        )
    for i in range(8):
        h = fake_hash(f"recap hash {i}")
        vectors.append(
            {"name": f"raw hash {i}", "recap_hash": to_hex(h), "echo_code": derive_echo_code(h)}
        )
    normalisation = [
        {"input": s, "normalized": normalize_code(s)}
        for s in [
            "7f3k",
            " 7F3K ",
            "7F3k",
            "OF3K",
            "of3k",
            "7FIK",
            "7FLK",
            "7F3U",
            "7F3",
            "7F3KK",
            "",
            "7F-K",
        ]
    ]
    try:
        derive_echo_code(b"short")
    except ValueError:
        pass
    else:  # pragma: no cover
        raise SystemExit("a short recap hash must be rejected")
    return {
        "description": "echo code: first 20 bits of H(0x50 || raw recap hash), Crockford base32",
        "vectors": vectors,
        "code_normalisation": normalisation,
        "rejected": [{"name": "recap hash of 5 bytes", "recap_hash_hex": b"short".hex()}],
    }


def chain_vectors() -> dict[str, Any]:
    sets = [
        [
            {"key": "price", "value": "4800000", "unit": "paise"},
            {"key": "qty", "value": "200", "unit": "shirts"},
        ],
        [
            {"key": "price", "value": "4800000", "unit": "paise"},
            {"key": "qty", "value": "200", "unit": "shirts"},
            {"key": "delivery", "value": "2026-11-15", "unit": "iso8601"},
        ],
        [
            {"key": "price", "value": "4800000", "unit": "paise"},
            {"key": "qty", "value": "200", "unit": "shirts"},
            {"key": "delivery", "value": "2026-11-22", "unit": "iso8601"},
        ],
    ]
    roots = [fake_hash(f"root {i}") for i in range(3)]
    digests = [terms_digest(s) for s in sets]
    links = chain_links(list(zip(digests, roots, strict=True)))
    entries = [
        {
            "version": i + 1,
            "terms_json": jtext(sets[i]),
            "terms_digest": to_hex(digests[i]),
            "root": to_hex(roots[i]),
            "link": to_hex(links[i]),
        }
        for i in range(3)
    ]
    changed: list[JsonValue] = [dict(s) for s in sets[0]]
    changed[0] = {**sets[0][0], "value": "4900000"}
    changed_links = chain_links(
        [(terms_digest(changed), roots[0]), (digests[1], roots[1]), (digests[2], roots[2])]
    )
    return {
        "description": "version chain: H(0x30 || previous link || terms digest || root)",
        "genesis": to_hex(bytes(32)),
        "versions": entries,
        "tampered_first_terms": {
            "terms_json": jtext(changed),
            "links": [to_hex(x) for x in changed_links],
        },
    }


